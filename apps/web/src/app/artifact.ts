import { Component, computed, input, signal } from '@angular/core';
import { NgIcon, provideIcons } from '@ng-icons/core';
import { HlmSkeletonImports } from '@spartan-ng/helm/skeleton';
import { MetricChart } from './metric-chart';
import { METRICS, NIGHTS, metricSeries } from './data';
import { ArtifactSpec, GenPhase } from './store';
import { phosphorChartBarLight, phosphorChartLineLight, phosphorDatabaseLight } from './icons';

/**
 * Renders an artifact spec. Every phase keeps the final dimensions, so nothing
 * shifts when the streamed props and then the data arrive.
 */
@Component({
  selector: 'app-artifact',
  imports: [NgIcon, MetricChart, HlmSkeletonImports],
  providers: [provideIcons({ phosphorChartLineLight, phosphorChartBarLight, phosphorDatabaseLight })],
  host: {
    class: 'block',
    '[attr.aria-busy]': "phase() !== 'done'",
  },
  template: `
    <div class="flex min-h-[46px] items-start justify-between gap-3">
      @if (phase() === 'choosing') {
        <div class="flex flex-col gap-2 pt-0.5" aria-hidden="true">
          <hlm-skeleton class="h-3 w-48" />
          <hlm-skeleton class="h-2.5 w-32" />
        </div>
      } @else {
        <div class="gen-in min-w-0">
          <p class="flex items-center gap-1.5 text-[14.5px] font-medium tracking-[-0.005em]">
            <span class="truncate">{{ spec().title }}</span>
            <span class="text-muted-foreground ring-border shrink-0 rounded px-1 text-[10px] font-medium tracking-[0.04em] ring-1" title="Generated by Compass">AI</span>
          </p>
          <p class="text-muted-foreground truncate text-[12.5px]">{{ spec().subtitle }}</p>
        </div>
        @if (spec().kind === 'line' && editable()) {
          <div class="bg-muted flex shrink-0 rounded-md p-0.5" role="group" aria-label="Chart type">
            <button type="button" class="grid size-6 place-items-center rounded-[5px] transition-colors" [class]="kind() === 'line' ? 'bg-card text-foreground shadow-xs' : 'text-muted-foreground hover:text-foreground'" [attr.aria-pressed]="kind() === 'line'" aria-label="Line chart" (click)="kind.set('line')" [disabled]="phase() !== 'done'"><ng-icon name="phosphorChartLineLight" class="text-[14px]" /></button>
            <button type="button" class="grid size-6 place-items-center rounded-[5px] transition-colors" [class]="kind() === 'bar' ? 'bg-card text-foreground shadow-xs' : 'text-muted-foreground hover:text-foreground'" [attr.aria-pressed]="kind() === 'bar'" aria-label="Bar chart" (click)="kind.set('bar')" [disabled]="phase() !== 'done'"><ng-icon name="phosphorChartBarLight" class="text-[14px]" /></button>
          </div>
        }
      }
    </div>

    <div class="relative mt-2" [style.height.px]="height()">
      @if (phase() === 'done') {
        @switch (spec().kind) {
          @case ('line') {
            <app-metric-chart
              class="gen-in -mx-1.5"
              [values]="line().ty"
              [compare]="line().ly"
              [dates]="line().dates"
              [format]="pct"
              [height]="height()"
              [kind]="kind()"
              [marks]="line().marks"
              [zeroBased]="true"
              [capAt]="100"
              [ariaLabel]="spec().title + ', this year versus last year'"
            />
          }
          @case ('bars') {
            <ul class="gen-in flex h-full flex-col justify-around" [attr.aria-label]="spec().title">
              @for (r of bars(); track r.label) {
                <li class="grid grid-cols-[92px_minmax(0,1fr)_96px] items-center gap-3 text-[13px]">
                  <span class="truncate">{{ r.label }}</span>
                  <span class="bg-foreground/6 relative h-2.5 overflow-hidden rounded-full">
                    <span class="bar-grow absolute inset-y-0 left-0 rounded-full" [class]="!anyHi() || r.hi ? 'bg-(--series)' : 'bg-(--series)/35'" [style.width.%]="(r.value / maxBar()) * 100"></span>
                  </span>
                  <span class="text-right tabular-nums"><span class="font-medium">{{ r.display ?? r.value + '%' }}</span> <span class="text-muted-foreground">{{ r.note }}</span></span>
                </li>
              }
            </ul>
          }
          @case ('columns') {
            <div class="gen-in flex h-full flex-col" role="img" [attr.aria-label]="colsLabel()">
              <div class="flex min-h-0 flex-1 items-end gap-[3px]">
                @for (c of cols(); track $index) {
                  <span class="min-w-0 flex-1 rounded-t-[3px]" [class]="!colsHi() || c.hi ? 'bg-(--series)' : 'bg-(--series)/35'" [style.height.%]="(c.value / maxCol()) * 100"></span>
                }
              </div>
              <div class="text-muted-foreground mt-1.5 flex justify-between gap-3 text-[11.5px] tabular-nums">
                <span>{{ cols()[0]?.label }} · {{ fmtCol(cols()[0]?.value ?? 0) }}</span>
                <span>{{ cols()[cols().length - 1]?.label }} · {{ fmtCol(cols()[cols().length - 1]?.value ?? 0) }}</span>
              </div>
            </div>
          }
        }
      } @else {
        <div class="absolute inset-0 flex flex-col justify-between py-2" aria-hidden="true">
          @for (i of [0, 1, 2, 3]; track i) {
            <div class="h-px bg-(--grid)"></div>
          }
        </div>
        @if (spec().kind === 'bars' && phase() !== 'choosing') {
          <div class="absolute inset-0 flex flex-col justify-around" aria-hidden="true">
            @for (w of [82, 54, 30, 26, 14]; track w) {
              <div class="grid grid-cols-[92px_minmax(0,1fr)] items-center gap-3">
                <hlm-skeleton class="h-2.5 w-16" />
                <hlm-skeleton class="h-2.5" [style.width.%]="w" />
              </div>
            }
          </div>
        } @else {
          <svg class="skeleton-wave absolute inset-x-0 bottom-5 h-[65%] w-full" viewBox="0 0 300 90" preserveAspectRatio="none" aria-hidden="true">
            <path d="M0,70 C30,62 45,40 75,44 S120,70 150,52 S210,20 240,30 S285,44 300,36 L300,90 L0,90 Z" class="fill-muted" />
          </svg>
        }
      }
    </div>

    <div class="border-border/70 mt-2 flex h-9 items-center justify-between gap-2 border-t text-[12px]">
      @switch (phase()) {
        @case ('choosing') {
          <span class="text-muted-foreground shimmer motion-reduce:shimmer-none">Choosing a component…</span>
        }
        @case ('props') {
          <span class="text-muted-foreground shimmer motion-reduce:shimmer-none">Building the query…</span>
        }
        @case ('data') {
          <span class="text-muted-foreground shimmer motion-reduce:shimmer-none">Running the query…</span>
        }
        @default {
          <span class="text-muted-foreground gen-in flex min-w-0 items-center gap-1.5">
            <ng-icon name="phosphorDatabaseLight" class="shrink-0 text-[14px]" />
            <span class="truncate font-mono text-[11.5px]">{{ spec().source }}</span>
          </span>
          @if (spec().kind === 'line') {
            <span class="text-(--brass-ink) gen-in flex shrink-0 items-center gap-1.5 font-medium">
              <i class="inline-block size-1.5 rounded-full bg-(--brass)"></i>{{ markLabel() }}
            </span>
          }
        }
      }
    </div>
  `,
})
export class ArtifactView {
  readonly spec = input.required<ArtifactSpec>();
  readonly phase = input<GenPhase>('done');
  readonly height = input(180);
  readonly editable = input(true);

  protected readonly kind = signal<'line' | 'bar'>('line');
  protected readonly pct = (n: number) => `${n.toFixed(0)}%`;

  protected readonly line = computed(() => {
    const s = this.spec();
    if (s.kind !== 'line') return { ty: [], ly: [], dates: [], marks: [] };
    const nights = NIGHTS.forward.slice(s.from, s.to);
    return {
      ty: metricSeries(nights, s.metric),
      ly: metricSeries(nights, s.metric, true),
      dates: nights.map((n) => n.date),
      marks: s.marks,
      label: METRICS[s.metric].label,
    };
  });
  protected readonly markLabel = computed(() => {
    const s = this.spec();
    return s.kind === 'line' ? s.markLabel : '';
  });
  protected readonly bars = computed(() => {
    const s = this.spec();
    return s.kind === 'bars' ? s.rows : [];
  });
  protected readonly maxBar = computed(() => Math.max(1, ...this.bars().map((r) => r.value)));
  protected readonly anyHi = computed(() => this.bars().some((r) => r.hi));
  protected readonly cols = computed(() => {
    const s = this.spec();
    return s.kind === 'columns' ? s.points : [];
  });
  protected readonly colsHi = computed(() => this.cols().some((c) => c.hi));
  protected readonly maxCol = computed(() => Math.max(1e-9, ...this.cols().map((c) => c.value)) * 1.08);
  protected fmtCol(v: number) {
    const s = this.spec();
    const unit = s.kind === 'columns' ? s.unit : '';
    return unit === '%' ? `${v.toFixed(v < 10 ? 2 : 0)}%` : Math.round(v).toLocaleString('en-GB');
  }
  protected readonly colsLabel = computed(() => {
    const c = this.cols();
    return c.length ? `${this.spec().title}: ${c[0].label} ${this.fmtCol(c[0].value)} to ${c[c.length - 1].label} ${this.fmtCol(c[c.length - 1].value)}` : this.spec().title;
  });
}
